// Lists every owner-fillable marker in the site: [VERIFY: ...], [LEGAL REVIEW REQUIRED: ...], [STAGE 3: ...].
// Usage: npm run placeholders | npm run placeholders:md (writes docs/PLACEHOLDERS.md) | npm run placeholders:gate (exit 1 if any remain)
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOTS = ['src', 'supabase', 'public', 'index.html'];
const PATTERN = /\[(VERIFY|LEGAL REVIEW REQUIRED|STAGE 3)[^\]]*\]/g;
const found = [];

function walk(path) {
  if (statSync(path).isDirectory()) {
    for (const name of readdirSync(path)) walk(join(path, name));
    return;
  }
  if (/\.(test\.tsx?|svg|css)$/.test(path)) return;
  readFileSync(path, 'utf8')
    .split('\n')
    .forEach((line, i) => {
      if (/^\s*(\/\/|\*|\/\*)/.test(line)) return; // skip code comments
      for (const m of line.matchAll(PATTERN))
        found.push({ file: relative('.', path).replaceAll('\\', '/'), line: i + 1, tag: m[1], text: m[0] });
    });
}
ROOTS.forEach(walk);

const out = found.map((f) => `${f.tag.padEnd(22)} ${f.file}:${f.line}  ${f.text}`).join('\n');
if (process.argv.includes('--md')) {
  const rows = found
    .map((f) => `| ${f.tag} | \`${f.file}:${f.line}\` | ${f.text.replaceAll('|', '\\|')} |`)
    .join('\n');
  writeFileSync(
    'docs/PLACEHOLDERS.md',
    `# Placeholders to fill before launch\n\nGenerated by \`npm run placeholders:md\`. Search the file and line, replace the whole bracketed marker with your real text, then re-run.\n\n| Tag | Location | Marker text |\n|---|---|---|\n${rows}\n`,
  );
  console.log(`Wrote docs/PLACEHOLDERS.md (${found.length} markers)`);
} else {
  console.log(out || 'No placeholders found.');
  console.log(`\n${found.length} marker(s).`);
}
if (process.argv.includes('--fail-if-any') && found.length > 0) process.exit(1);
